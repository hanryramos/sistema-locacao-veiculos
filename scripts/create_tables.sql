/*
    Sistema de Locação de Veículos
    Script de criação das tabelas, chaves, restrições e sequences.

    Execute este script com o mesmo usuário configurado em
    src/conexion/passphrase/authentication.oracle (esse usuário será o
    dono das tabelas).

    Observação: na primeira execução, os comandos DROP abaixo podem gerar
    erro ORA-00942 (tabela/sequence inexistente). Isso é esperado.
*/

/* Apaga os relacionamentos e as tabelas, caso já existam */
DROP TABLE LOCACOES CASCADE CONSTRAINTS;
DROP TABLE VEICULOS CASCADE CONSTRAINTS;
DROP TABLE CLIENTES CASCADE CONSTRAINTS;

/* Apaga as sequences, caso já existam */
DROP SEQUENCE LOCACOES_ID_SEQ;
DROP SEQUENCE VEICULOS_ID_SEQ;
DROP SEQUENCE CLIENTES_ID_SEQ;

/* Cria as tabelas */
CREATE TABLE CLIENTES (
    ID NUMBER NOT NULL,
    NOME VARCHAR2(255) NOT NULL,
    CPF VARCHAR2(11) NOT NULL,
    TELEFONE VARCHAR2(20) NOT NULL,
    CONSTRAINT CLIENTES_PK PRIMARY KEY (ID),
    CONSTRAINT CLIENTES_CPF_UK UNIQUE (CPF)
);

CREATE TABLE VEICULOS (
    ID NUMBER NOT NULL,
    MODELO VARCHAR2(100) NOT NULL,
    PLACA VARCHAR2(10) NOT NULL,
    ANO NUMBER(4) NOT NULL,
    VALOR_DIARIA NUMBER(10,2) NOT NULL,
    CONSTRAINT VEICULOS_PK PRIMARY KEY (ID),
    CONSTRAINT VEICULOS_PLACA_UK UNIQUE (PLACA),
    CONSTRAINT VEICULOS_ANO_CK CHECK (ANO BETWEEN 1900 AND 2100),
    CONSTRAINT VEICULOS_VALOR_DIARIA_CK CHECK (VALOR_DIARIA > 0)
);

CREATE TABLE LOCACOES (
    ID NUMBER NOT NULL,
    ID_CLIENTE NUMBER NOT NULL,
    ID_VEICULO NUMBER NOT NULL,
    DATA_RETIRADA DATE NOT NULL,
    DATA_DEVOLUCAO DATE NOT NULL,
    VALOR_TOTAL NUMBER(10,2) NOT NULL,
    CONSTRAINT LOCACOES_PK PRIMARY KEY (ID),
    CONSTRAINT LOCACOES_DATAS_CK CHECK (DATA_DEVOLUCAO >= DATA_RETIRADA),
    CONSTRAINT LOCACOES_VALOR_TOTAL_CK CHECK (VALOR_TOTAL >= 0)
);

/* Cria as sequences utilizadas para gerar as chaves primárias */
CREATE SEQUENCE CLIENTES_ID_SEQ START WITH 1 INCREMENT BY 1;
CREATE SEQUENCE VEICULOS_ID_SEQ START WITH 1 INCREMENT BY 1;
CREATE SEQUENCE LOCACOES_ID_SEQ START WITH 1 INCREMENT BY 1;

/* Cria os relacionamentos (chaves estrangeiras) */
ALTER TABLE LOCACOES ADD CONSTRAINT CLIENTES_LOCACOES_FK
FOREIGN KEY (ID_CLIENTE)
REFERENCES CLIENTES (ID)
NOT DEFERRABLE;

ALTER TABLE LOCACOES ADD CONSTRAINT VEICULOS_LOCACOES_FK
FOREIGN KEY (ID_VEICULO)
REFERENCES VEICULOS (ID)
NOT DEFERRABLE;
